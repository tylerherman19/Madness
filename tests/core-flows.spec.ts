test('signed email callbacks suppress bounced recipients and reject forged signatures',async({request})=>{
 const payload=JSON.stringify({type:'email.bounced',created_at:new Date().toISOString(),data:{to:['bounced@example.test'],email_id:'fixture'}})
 const id='msg_fixture',timestamp=String(Math.floor(Date.now()/1000))
 const signature=createHmac('sha256',Buffer.alloc(32,7)).update(`${id}.${timestamp}.${payload}`).digest('base64')
 const headers={'Content-Type':'application/json','svix-id':id,'svix-timestamp':timestamp,'svix-signature':`v1,${signature}`}
 expect((await request.post('/api/webhooks/email',{headers,data:payload})).ok()).toBeTruthy()
 expect((await request.post('/api/webhooks/email',{headers,data:payload})).ok()).toBeTruthy()
 expect((await request.post('/api/webhooks/email',{headers:{...headers,'svix-signature':'v1,invalid'},data:payload})).status()).toBe(401)
})

test('a deadline crossing blocks edits while an identical accepted retry retains its receipt',async({request})=>{
 await request.post('/api/auth/login',{data:{email:'player+test@example.test',password:'FixturePass123!'}})
 const accepted=await request.post('/api/picks',{data:{slate_id:slate,team:'A'}})
 expect(accepted.ok()).toBeTruthy()
 const saved=(await accepted.json()).pick
 await request.post('http://127.0.0.1:54329/__test/lock')
 const late=await request.post('/api/picks',{data:{slate_id:slate,team:'B',pick_id:saved.id,expected_version:saved.updated_at}})
 expect(late.status()).toBe(400)
 const retry=await request.post('/api/picks',{data:{slate_id:slate,team:'A'}})
 expect(retry.ok()).toBeTruthy()
 expect((await retry.json()).pick.id).toBe(saved.id)
})
